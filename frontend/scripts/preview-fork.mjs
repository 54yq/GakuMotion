import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { resolve, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { chromium } from 'playwright'

const [preview, output, executablePath] = process.argv.slice(2)
if (!preview || !output) throw new Error('Pass the built preview directory and the design output directory.')
const previewDir = resolve(preview)
const outputDir = resolve(output)
await mkdir(outputDir, { recursive: true })
const html = await readFile(join(previewDir, 'index.html'), 'utf8')
const jsPath = html.match(/<script type="module"[^>]*src="([^"]+)"><\/script>/)?.[1]
const cssPath = html.match(/<link rel="stylesheet"[^>]*href="([^"]+)">/)?.[1]
if (!jsPath || !cssPath) throw new Error('Expected a single local JS bundle and stylesheet.')
const [js, css] = await Promise.all([readFile(join(previewDir, jsPath), 'utf8'), readFile(join(previewDir, cssPath), 'utf8')])
let inlineJs = js.replace(/<\/script/gi, '<\\/script')
for (const asset of await readdir(join(previewDir, 'assets'))) {
  if (!asset.endsWith('.svg')) continue
  const image = await readFile(join(previewDir, 'assets', asset))
  const dataUrl = 'data:image/svg+xml;base64,' + image.toString('base64')
  inlineJs = inlineJs.replaceAll('./assets/' + asset, dataUrl).replaceAll('assets/' + asset, dataUrl).replaceAll(asset, dataUrl)
}
const parserHash = createHash('sha256').update(inlineJs).digest('base64')
const inline = html.replace("script-src 'self'", `script-src 'self' 'sha256-${parserHash}'`)
  .replace(/<script type="module"[^>]*src="[^"]+"><\/script>/, () => `<script type="module">${inlineJs}</script>`)
  .replace(/<link rel="stylesheet"[^>]*href="[^"]+">/, () => `<style>${css}</style>`)
const entry = join(previewDir, 'Open-Preview.html')
await writeFile(entry, inline, 'utf8')

const browser = await chromium.launch({ executablePath, headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1040, height: 880 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(pathToFileURL(entry).href + '?preview=1')
  await page.getByTestId('library-page').waitFor()
  await page.getByRole('button', { name: 'Live 接管中', exact: true }).waitFor()
  await page.getByText('Starlight Step', { exact: true }).dblclick()
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  const progress = page.getByRole('slider', { name: '播放进度', exact: true }).first()
  await progress.waitFor()
  await page.getByRole('img', { name: 'GakuMotion', exact: true }).evaluate(img => img.decode())
  const bar = await page.getByTestId('transport-bar').boundingBox()
  if (!bar) throw new Error('The transport bar is not visible.')
  await page.mouse.click(bar.x + bar.width * 0.38, bar.y + 1)
  await page.mouse.move(bar.x + bar.width * 0.38, bar.y + 1)
  await page.screenshot({ path: join(outputDir, '01-library-and-transport.png') })
  await page.getByRole('button', { name: '精细控制', exact: true }).click()
  await page.screenshot({ path: join(outputDir, '04-precision-controls.png') })
  await page.keyboard.press('Escape')
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '动作', exact: true }).click()
  const heading = page.getByLabel('初始位置 朝向', { exact: true })
  await heading.waitFor()
  const initialHeading = parseFloat(await heading.inputValue())
  await heading.press('ArrowRight')
  if (parseFloat(await heading.inputValue()) !== initialHeading + 1) throw new Error('Primary heading did not change.')
  await page.getByText('初始角色位置偏移', { exact: true }).evaluate(element => element.scrollIntoView({ block: 'center' }))
  await page.screenshot({ path: join(outputDir, '05-placement-and-heading.png') })
  const ensemble = page.getByTestId('motion-ensemble')
  const trigger = ensemble.getByRole('button', { name: /多人舞台/ })
  if (await trigger.getAttribute('aria-expanded') !== 'true') await trigger.click()
  const primary = ensemble.getByRole('region', { name: '主角色', exact: true })
  await primary.getByText('物理：原生物理运行中', { exact: true }).waitFor()
  const primaryHeading = primary.locator('dd').last()
  if (await primaryHeading.textContent() !== `${(initialHeading + 1).toFixed(1)}°`) throw new Error('Primary card did not reflect the heading edit.')
  if (await primary.getByRole('textbox').count() || await primary.getByRole('button').count()) throw new Error('Primary card still exposes placement editing.')
  const primaryX = page.getByLabel('初始位置 X', { exact: true })
  const initialX = parseFloat(await primaryX.inputValue())
  await primaryX.press('ArrowRight')
  if (await primary.locator('dd').first().textContent() !== (initialX + 0.01).toFixed(2)) throw new Error('Primary card did not reflect the X edit.')
  await primaryX.press('ArrowLeft')
  await ensemble.getByRole('heading', { name: '副角色 2', exact: true }).waitFor()
  await ensemble.getByRole('button', { name: '添加副角色' }).click()
  await ensemble.getByRole('button', { name: '添加副角色' }).click()
  await ensemble.getByRole('heading', { name: '副角色 4', exact: true }).waitFor()
  await ensemble.getByRole('option', { name: '新模型 B' }).first().waitFor({ state: 'attached' })
  await ensemble.getByLabel('副角色 1 站位 朝向', { exact: true }).waitFor()
  const lateral = ensemble.getByLabel('副角色 1 站位 X', { exact: true })
  await lateral.scrollIntoViewIfNeeded()
  const bounds = await lateral.boundingBox()
  if (!bounds) throw new Error('The follower placement input is not visible.')
  const x = bounds.x + bounds.width / 2
  const y = bounds.y + bounds.height / 2
  const start = parseFloat(await lateral.inputValue())
  for (const direction of [1, -1]) {
    await page.mouse.move(x, y)
    await page.mouse.down()
    await page.mouse.move(x + 20 * direction, y, { steps: 5 })
    await page.mouse.up()
    const actual = parseFloat(await lateral.inputValue())
    if (direction === 1 ? actual <= start : actual !== start) throw new Error('Follower X did not follow the horizontal drag.')
  }
  if (await ensemble.getByText('队形预设', { exact: true }).count()) throw new Error('Ensemble preset UI is still visible.')
  await page.setViewportSize({ width: 1040, height: 1100 })
  await ensemble.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: join(outputDir, '02-formation.png') })
  await page.setViewportSize({ width: 1040, height: 880 })
  await page.getByRole('button', { name: /高级动作设置/ }).click()
  await page.getByLabel('前臂轴向校正', { exact: true }).waitFor()
  await page.getByRole('button', { name: /高级动作设置/ }).evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: join(outputDir, '06-advanced-motion.png') })
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '镜头', exact: true }).click()
  await page.getByRole('checkbox', { name: '镜头随主角色朝向', exact: true }).check()
  await page.getByRole('checkbox', { name: '关闭 Live 景深', exact: true }).check()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '舞台', exact: true }).click()
  await page.getByRole('button', { name: /高级场景编辑/ }).click()
  await page.getByRole('checkbox', { name: '隐藏 咲季 麦克风', exact: true }).check()
  await page.getByRole('button', { name: /高级场景编辑/ }).evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.screenshot({ path: join(outputDir, '07-stage-prop-nodes.png') })
  await page.getByRole('button', { name: 'Live 接管中', exact: true }).click()
  await page.getByRole('button', { name: '退出接管并恢复 Live', exact: true }).waitFor()
  await page.getByText('诊断与测试', { exact: true }).click()
  await page.getByRole('button', { name: '读取上次 Swing 报告', exact: true }).click()
  await page.getByText(/已读取 Swing 报告/).waitFor()
  await page.screenshot({ path: join(outputDir, '03-live-takeover.png') })
  await page.getByRole('button', { name: '退出接管并恢复 Live', exact: true }).click()
  await page.getByRole('button', { name: '启动 Live 接管', exact: true }).waitFor()
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('Design smoke: library, transport, read-only primary placement and physics, follower placement, dynamic slots, advanced motion, camera, props and Live diagnostics verified.')
} finally {
  await browser.close()
}
