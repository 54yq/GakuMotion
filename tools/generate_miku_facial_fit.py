"""Validate explicit offline portable profiles and generate standalone C++ data.

No private model, UnityPy, game installation path, or offline Python dependency
is needed by the resulting DLL. Asset hashes record export provenance only.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
from pathlib import Path


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def shape(value, dimensions):
    if not dimensions:
        return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)
    return isinstance(value, list) and len(value) == dimensions[0] and all(shape(item, dimensions[1:]) for item in value)


def validate(profile):
    role = profile['character']
    assert role in ['kcna', 'atbm', 'hmsz', 'amao']
    assert profile['face_bundle'] == f'mdl_chr_{role}-base-0000_face'
    for key in ['face_cache_sha256', 'frozen_mapping_sha256']:
        assert len(profile[key]) == 64 and set(profile[key]) <= set('0123456789abcdef')
    names = profile['output_shapes']
    assert len(names) == len(set(names)) == 9
    assert all(name.startswith('b_mouth.mouth_') for name in names)
    assert names[-2:] == ['b_mouth.mouth_026', 'b_mouth.mouth_028']
    for key, dimensions in [('inputs', [27, 5]), ('outputs', [27, 9]),
                             ('simplices', [36, 6]), ('inverse_augmented_matrices', [36, 6, 6])]:
        assert shape(profile[key], dimensions), key
    points, outputs = profile['inputs'], profile['outputs']
    assert len(set(map(tuple, points))) == 27
    for point in points:
        assert all(0 <= x <= 1 for x in point) and sum(point) <= 1+1e-12
    for output in outputs:
        assert all(0 <= x <= 1 for x in output) and sum(output[-2:]) <= 1+1e-10
    origin = [index for index, point in enumerate(points) if not any(point)]
    assert len(origin) == 1 and not any(outputs[origin[0]])
    cells = profile['simplices']
    assert cells == sorted(cells) and len(set(map(tuple, cells))) == 36
    assert set(index for cell in cells for index in cell) == set(range(27))
    for cell, inverse in zip(cells, profile['inverse_augmented_matrices']):
        assert cell == sorted(cell) and len(set(cell)) == 6
        assert all(isinstance(index, int) and not isinstance(index, bool) and 0 <= index < 27 for index in cell)
        matrix = [[points[index][axis] for index in cell] for axis in range(5)]+[[1.]*6]
        error = max(abs(sum(inverse[row][inner]*matrix[inner][column] for inner in range(6))-(row == column))
                    for row in range(6) for column in range(6))
        assert error < 1e-8, f'{role}: invalid frozen inverse'


def initializer(value):
    if isinstance(value, list):
        return '{{'+', '.join(initializer(item) for item in value)+'}}'
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    return format(value, '.17g')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', nargs='+', type=Path, required=True)
    parser.add_argument('--json-out', type=Path, required=True)
    parser.add_argument('--header-out', type=Path, required=True)
    args = parser.parse_args()
    profiles = []
    for path in args.input:
        document = json.loads(path.read_text(encoding='utf-8'))
        assert document['schema'] == 'gakumotion.miku_mouth_fit/1'
        assert document['source_vowels'] == ['a', 'i', 'u', 'e', 'o']
        for profile in document['characters']:
            validate(profile)
            profiles.append(profile)
    assert len(profiles) == 4 and {p['character'] for p in profiles} == {'kcna', 'atbm', 'hmsz', 'amao'}
    profiles.sort(key=lambda item: item['character'])
    document = {'schema': 'gakumotion.miku_mouth_fit/1', 'source_vowels': ['a', 'i', 'u', 'e', 'o'],
                'characters': profiles,
                'generation': {'tool_sha256': digest(__file__),
                               'source_portable_sha256': [digest(path) for path in args.input],
                               'runtime_asset_bytes_verified': False}}
    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    args.json_out.write_text(json.dumps(document, ensure_ascii=False, indent=2, allow_nan=False)+'\n', encoding='utf-8', newline='\n')
    declarations = '''#pragma once
#include <array>
// GENERATED by tools/generate_miku_facial_fit.py; do not edit coefficients.
// Source portable JSON SHA256: PORTABLE_SHA
// Asset hashes are export provenance; runtime checks actual face GameObject name, not asset bytes.
namespace GakuMotion
{
    struct MikuMouthFitProfile
    {
        const char* character;
        const char* faceName;
        const char* mappingSha256;
        const char* sourceCacheSha256;
        std::array<const char*, 9> shapes;
        std::array<std::array<double, 5>, 27> inputs;
        std::array<std::array<double, 9>, 27> outputs;
        std::array<std::array<unsigned, 6>, 36> cells;
        std::array<std::array<std::array<double, 6>, 6>, 36> inverses;
    };
    inline constexpr std::array<MikuMouthFitProfile, 4> kMikuMouthFits{{
'''.replace('PORTABLE_SHA', digest(args.json_out))
    for profile in profiles:
        values = [profile['character'], profile['face_bundle'], profile['frozen_mapping_sha256'],
                  profile['face_cache_sha256'], profile['output_shapes'], profile['inputs'],
                  profile['outputs'], profile['simplices'], profile['inverse_augmented_matrices']]
        declarations += '        MikuMouthFitProfile{\n            '+',\n            '.join(initializer(value) for value in values)+'\n        },\n'
    declarations += '    }};\n}\n'
    args.header_out.parent.mkdir(parents=True, exist_ok=True)
    args.header_out.write_text(declarations, encoding='utf-8', newline='\n')
    print(json.dumps({'profiles': [p['character'] for p in profiles], 'json_sha256': digest(args.json_out),
                      'header_sha256': digest(args.header_out)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
